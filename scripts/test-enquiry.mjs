import assert from "node:assert/strict";
import { prepareEnquiry } from "../lib/enquiry.ts";
const valid = { name: "Ada Example", email: "ada@example.com", company: "Example & Co", type: "PADI product vision", source: "Referral", message: "Hello & thank you.\nCan we discuss PADI?" };
const draft = prepareEnquiry(valid);
assert.equal(draft.copyFirst, false);
const link = new URL(draft.href);
assert.equal(link.pathname, "admin@lightways.tech");
assert.equal(link.searchParams.get("body"), draft.body);
assert.match(draft.body, /Hello & thank you\.\nCan we discuss PADI\?/);
assert.equal(link.searchParams.get("subject"), draft.subject);
for (const change of [{ name: " " }, { email: "not-an-email" }, { message: " " }, { message: "x".repeat(5001) }]) assert.throws(() => prepareEnquiry({ ...valid, ...change }));
const long = prepareEnquiry({ ...valid, message: "x".repeat(2000) });
assert.equal(long.copyFirst, true);
assert.equal(new URL(long.href).searchParams.has("body"), false);
const untrusted = prepareEnquiry({ ...valid, name: "Ada\r\nBcc: other@example.com", type: "Injected type", source: "Injected source" });
assert.match(untrusted.body, /Name: Ada Bcc: other@example.com\n/);
assert.equal(new URL(untrusted.href).searchParams.has("bcc"), false);
assert.match(untrusted.subject, /General question$/);
assert.match(untrusted.body, /Not specified/);
console.log("Enquiry validation, encoding, header isolation and long-draft fallback passed.");
